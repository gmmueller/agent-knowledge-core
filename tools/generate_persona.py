"""Generate a thin persona skill from a brain's brain.md (pipeline step 8).

Usage: python -I tools/generate_persona.py --brain <brain-folder> --out <skills-directory>
The output root can instead be supplied by AGENT_KNOWLEDGE_CORE_SKILLS_DIR.
Optional <workspace>/workspace.yaml `user_persona_skills: [name, ...]` names the user's own persona skills,
so the generated skill can point at them ("e.g. ...") when it says to keep the two views apart.
The core wording is subject-neutral. Optional brain.md `skill.guidance: [...]` adds a "This brain's guidance"
section and `skill.boundaries: [...]` adds boundary bullets, for anything specific to the brain's subject.
When a brain has no guidance yet, the tool prints content-based suggestions ("consider skill.guidance: ...").
Writes <out>/<name>/SKILL.md and <out>/<name>/agents/openai.yaml.
Use --check to report drift or missing files without writing. Regenerate to update the skill.
"""
import argparse
import json
import os
import sys
import pathlib
import re

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))  # python -I drops the script dir
import brainlib
from reference_sources import enabled as reference_mode


SKILL = """---
name: {name}
description: {description}
---

<!-- Generated by tools/generate_persona.py from {brain_md} (updated {updated}). Don't edit here: change brain.md and regenerate. -->

# {display_name}

A persona compiled from primary sources into a cited wiki. Its knowledge lives in the brain folder, not in this file:

- **Persona card:** `{brain_md}`. Scope, voice, worldview, rules, framework map, task loop and boundaries.
- **Wiki:** `{wiki}`. Concept pages are in `topics/`, `principles/`, `frameworks/`, `methods/`, `rules/` and `glossary/`, and per-lesson pages are in `sources/`.{examples_folder}
- **Transcripts:** `{raw}`. Use them for exact wording and surrounding context.
{tools_folder}
## How to use it

1. **Load.** On first use in a task, read `brain.md` and the concept index `wiki/index.md`.
2. **Look up.** Search qmd collections `{name}-wiki` and `{name}-raw` when available, or grep `wiki/` and `raw/`. Read the relevant concept pages{examples_lookup}, then their source pages or raw transcripts for exact quotes. Open `wiki/sources-index.md` only to locate a specific source. For a broad question that needs many pages, delegate the reading to one subagent and ask for a cited answer.
3. **Answer** by following the persona card's **Task loop**: clarify the goal and situation, find the matching framework, answer in the persona's structure and voice, check the advice against its rules, and flag limits.
4. **Cite** claims and quotes as wiki page names or `([[raw/<path>]] @ m:ss)` (or the other citation forms the persona card lists), writing the full path every time (no "same lesson" shorthand), so citations can be checked. Quotes must be exact. A quote with no speaker name is {persona}'s; anyone else's is labelled on the quote line, so keep the label.
5. **Stay inside the material.** Anything the wiki doesn't support is **Inference:**. Say "the material doesn't cover this" rather than inventing an answer. Numbers and details are as recorded in the material, so note when they may be out of date.
{guidance}
## Boundaries

- **Read-only.** Don't edit the brain from here. Updates go through the brains repo (`docs/updates.md`: refresh, ingest, lint).
- **Separate voice.** This is what {persona}'s material teaches. Keep it distinct from the user's own persona skills{own_skills}. When both are used, say which view is which.
- **No side effects.** Advice and drafts only: no posting, spending or account changes because the persona recommends it.
{boundaries}"""


TOPIC_SKILL = """---
name: {name}
description: {description}
---

<!-- Generated by tools/generate_persona.py from {brain_md} (updated {updated}). Don't edit here: change brain.md and regenerate. -->

# {display_name}

{topic_intro} Its knowledge lives in the brain folder, not in this file:

- **Brain card:** `{brain_md}`: scope, {topic_catalog}, extraction areas, task loop and boundaries.
- **Wiki:** `{wiki}`. Concept pages are in `topics/`, `principles/`, `frameworks/`, `methods/`, `rules/`, {rubrics_folder}`debates/` and `glossary/`. Per-source pages are in `sources/`.{examples_folder}
- **Library:** `{library}`. Transcripts and pages shared across brains, cited as `[[library/<publisher>/raw/...]]`.
{tools_folder}
## How to use it

1. **Load.** On first use in a task, read `brain.md` and the concept index `wiki/index.md`.
2. **Look up.** Search qmd collections `{name}-wiki` and `library` when available, or grep `wiki/` and `library/*/raw/`{local_lookup}. Read the relevant {topic_lookup}{examples_lookup}, then their source pages or {topic_raw} for exact quotes. Open `wiki/sources-index.md` only to locate a specific source. For a broad request that needs many pages, delegate the reading to one subagent and ask for a cited answer.
3. **Do the work** following the brain card's **Task loop**: clarify the job and context, {topic_action}{topic_check}.
4. **Weigh the evidence.** {topic_evidence}
5. **Cite** as wiki page names or `([[library/<publisher>/raw/<path>]] @ <block>)`, writing the full path every time. {topic_citation}
6. **Stay inside the material.** Anything the wiki doesn't support is **Inference:**. Say "the material doesn't cover this" rather than inventing facts or rules.
{guidance}
## Boundaries

- **Read-only.** Don't edit the brain from here. Updates go through the brains repo (`docs/updates.md`, `docs/library.md`).
- **Scope.** Hand off what the brain card lists as out of scope to the named sibling brain, or say it's outside this brain.
- **Separate from the user's own persona skills**{own_skills}: when both are used, say which view is which.
- **No side effects.** Advice and drafts only: no posting, spending or account changes.
{boundaries}"""


def topic_wording(brain, settings, experts):
    wiki = brain / "wiki"
    rubrics = any((wiki / "rubrics").glob("*.md"))
    lookup = "concept, rule and rubric pages" if rubrics else "concept and rule pages"
    check = ", check the result against the relevant rubric, and show the check" if rubrics else ""
    if not rubrics:
        checklists = [p.name for p in sorted((wiki / "methods").glob("*.md"))
                      if "checklist" in p.stem.lower()
                      or re.search(r"^#+ .*\bchecklists?\b", p.read_text(encoding="utf-8"), re.I | re.M)]
        if checklists:
            lookup += ", plus the applicable checklist in `methods/` (" + ", ".join(f"`{name}`" for name in checklists) + ")"
            check = ", check the result against the applicable checklist, and show the check"
    values = {
        "topic_lookup": lookup,
        "topic_check": check,
        "rubrics_folder": "`rubrics/`, " if rubrics else "",
    }
    if reference_mode(settings):
        return {**values,
                "topic_intro": "A topic specialist compiled from reference documents into a cited wiki.",
                "topic_catalog": "sources",
                "local_lookup": " (also `raw/` for brain-local sources)",
                "topic_raw": "captured documents",
                "topic_action": "apply the current reference documents",
                "topic_evidence": "Prefer current authoritative documents. Use `bench` rules with caution. "
                                  "For `contested` rules, show where current sources differ.",
                "topic_citation": "Give the source title, its version or publication date when known, and the exact "
                                  "locator. Check source pages and `sources.yaml` for edition metadata. Copy quotes "
                                  "verbatim from the cited source."}
    return {**values,
            "topic_intro": f"A topic specialist compiled from several experts' own material ({experts}) into a cited wiki. "
                           "It has no imitated voice: it applies the experts' methods and says whose method each step comes from.",
            "topic_catalog": "experts",
            "local_lookup": "",
            "topic_raw": "library transcripts",
            "topic_action": "apply the experts' methods (naming whose)",
            "topic_evidence": "Prefer `consensus` rules (several experts agree), then `active`, then `bench`. "
                              "When experts disagree, present the debate page's positions instead of picking silently.",
            "topic_citation": "Quotes are exact and always name their speaker: copy them from the source or raw text, "
                              "and if you paraphrase, drop the quote marks."}


def _lines(value, key):
    if value is None:
        return []
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, list) or not all(isinstance(v, str) and v.strip() for v in value):
        raise ValueError(f"brain.md skill.{key} must be a list of non-empty strings")
    return [v.strip() for v in value]


def customization(brain, fm):
    """Template values that come from the brain itself: its folders and its own skill.guidance / skill.boundaries.

    The core wording stays subject-neutral. Anything specific to a brain's subject (platforms, safety limits,
    house rules) belongs in that brain's brain.md under skill.guidance (extra instructions) and skill.boundaries
    (extra boundary bullets), so it reaches only that brain's skill.
    """
    skill = fm.get("skill") or {}
    guidance = _lines(skill.get("guidance"), "guidance")
    boundaries = _lines(skill.get("boundaries"), "boundaries")
    examples = any((brain / "wiki" / "examples").glob("*.md"))
    return {
        "examples_folder": " Worked examples are in `examples/`." if examples else "",
        "examples_lookup": ", plus examples when a demonstration helps" if examples else "",
        "guidance": ("\n## This brain's guidance\n\n" + "".join(f"- {g}\n" for g in guidance)) if guidance else "",
        "boundaries": "".join(f"- {b}\n" for b in boundaries),
    }


def suggestions(brain, fm):
    """Content-based hints for skill.guidance, printed (never written) when the brain has none yet."""
    if (fm.get("skill") or {}).get("guidance"):
        return []
    hints = []
    wiki = brain / "wiki"
    pages = [p.read_text(encoding="utf-8") for p in wiki.rglob("*.md")] if wiki.is_dir() else []
    evidence = [str(e) for e in fm.get("evidence_types") or []]
    if "official" in evidence or fm.get("official"):
        hints.append("the brain cites official sources: say when they outrank practitioner claims, and to give their dates")
    dated = sum(1 for t in pages if re.search(r"^freshness:\s*(?!evergreen\b)\S+", t, re.M))
    if dated:
        hints.append(f"{dated} pages are marked time-sensitive (freshness): say to date such claims and prefer the newest source")
    if any((wiki / "examples").glob("*.md")):
        hints.append("the brain has worked examples: say what they show and what they don't (one case doesn't generalise)")
    if {"practitioner", "creator"} & set(evidence) and ("official" in evidence or fm.get("official")):
        hints.append("practitioners and official sources both appear: say how to label a practitioner's claim about how a system works")
    if fm.get("hosts"):
        hints.append("the brain has interviewers (hosts): their claims never back a rule, so say how to treat them in answers")
    return hints


def main() -> None:
    ap = argparse.ArgumentParser()
    brainlib.add_brain_arg(ap)
    ap.add_argument("--out", default=os.environ.get("AGENT_KNOWLEDGE_CORE_SKILLS_DIR"), help="root directory for generated skills")
    ap.add_argument("--relative-to", type=pathlib.Path, metavar="DIR", help="write portable paths relative to DIR; default: absolute paths")
    ap.add_argument("--check", action="store_true", help="exit 1 if generated files are missing or differ; write nothing")
    a = ap.parse_args()
    if not a.out:
        ap.error("--out or AGENT_KNOWLEDGE_CORE_SKILLS_DIR is required")
    brain = brainlib.brain_dir(a.brain)
    text = (brain / "brain.md").read_text(encoding="utf-8")
    fm = yaml.safe_load(re.match(r"^---\n(.*?)\n---\n", text, re.S).group(1))
    skill = fm["skill"]
    values = {
        "name": fm["name"],
        "description": json.dumps(skill["description"], ensure_ascii=False),
        "display_name": fm["display_name"],
        "persona": re.sub(r"^.*\((.*)\)$", r"\1", fm["display_name"]),
        "brain_md": str(brain / "brain.md"),
        "wiki": str(brain / "wiki"),
        "raw": str(brain / "raw"),
        "tools": str(brain / "tools"),
        "updated": fm.get("updated"),
        "experts": ", ".join(fm.get("experts") or []),
        "library": str(brainlib.library_dir(brainlib.workspace(brain))),
        "own_skills": "",
    }
    own = (brainlib.load_yaml(brainlib.workspace(brain) / "workspace.yaml", {}) or {}).get("user_persona_skills") or []
    if own:
        values["own_skills"] = f" (e.g. {', '.join(own)})"
    if a.relative_to is not None:
        root = a.relative_to.expanduser().resolve()
        for key in ("brain_md", "wiki", "raw", "tools", "library"):
            values[key] = pathlib.Path(os.path.relpath(values[key], root)).as_posix()
    values["tools_folder"] = f"- **Tools:** `{values['tools']}` holds brain-specific tools.\n" if (brain / "tools").is_dir() else ""
    wiki_tools = sorted(p.name for p in brainlib.iter_files(brain / "wiki" / "tools") if p.suffix == ".md")
    if wiki_tools:
        names = ", ".join(f"`{name}`" for name in wiki_tools)
        values["tools_folder"] += f"- **Tool pages:** Find {names} in `{values['wiki']}/tools/`.\n"
    name = str(fm["name"])
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
        ap.error("brain.md name must be a kebab-case slug")
    out = pathlib.Path(a.out).expanduser().resolve() / name
    try:
        values.update(customization(brain, fm))
    except ValueError as error:
        ap.error(str(error))
    template = TOPIC_SKILL if fm.get("kind") == "topic" else SKILL
    if template == TOPIC_SKILL:
        values.update(topic_wording(brain, fm, values["experts"]))
    rendered = template.format(**values)
    if a.relative_to is not None:
        comment = "<!-- Portable example: normal generate_persona.py use writes absolute paths for your own machine. Paths here are relative to the --relative-to root; regenerate without that flag for installation elsewhere. -->\n\n"
        rendered = rendered.replace("<!-- Generated by", comment + "<!-- Generated by", 1)
    openai = {"interface": {"display_name": fm["display_name"], "short_description": skill["short_description"],
                            "default_prompt": skill["default_prompt"]}}
    files = {"SKILL.md": rendered, "agents/openai.yaml": yaml.safe_dump(openai, sort_keys=False, allow_unicode=True, width=200)}
    if a.check:
        changes = []
        for name, content in files.items():
            try:
                installed = (out / name).read_bytes()
            except FileNotFoundError:
                changes.append(f"{name} (missing)")
                continue
            if installed.replace(b"\r\n", b"\n") != content.encode("utf-8"):
                changes.append(f"{name} (changed)")
        if changes:
            print(f"Skill drift in {out} ({', '.join(changes)}). Regenerate without --check.")
            sys.exit(1)
        print(f"Skill is current in {out}")
        return
    (out / "agents").mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {out / 'SKILL.md'} and agents/openai.yaml ({len(skill['description'])}-char description)")
    for hint in suggestions(brain, fm):
        print(f"consider skill.guidance: {hint}")


if __name__ == "__main__":
    main()
